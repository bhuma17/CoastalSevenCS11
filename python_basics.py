def student_grade_calculator(marks):
    """marks: dict of subject -> score (0-100)"""
    if not marks:
        raise ValueError("No marks provided")

    total = sum(marks.values())
    average = total / len(marks)

    if average >= 90:
        grade = "A"
    elif average >= 75:
        grade = "B"
    elif average >= 60:
        grade = "C"
    elif average >= 40:
        grade = "D"
    else:
        grade = "F"

    return {"total": total, "average": round(average, 2), "grade": grade}



marks = {"Math": 85, "Science": 92, "English": 78}
result = student_grade_calculator(marks)
print("Marks:", marks)
print("Result:", result)

def factorial(n):
    if n < 0:
        raise ValueError("Factorial not defined for negative numbers")
    result = 1
    for i in range(2, n + 1):
        result *= i
    return result


def reverse_string(s):
    return s[::-1]


def is_palindrome(s):
    cleaned = s.replace(" ", "").lower()
    return cleaned == cleaned[::-1]




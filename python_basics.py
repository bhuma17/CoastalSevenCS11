from fastapi import FastAPI, HTTPException
from pydantic import BaseModel
from typing import Optional

app = FastAPI(title="Student API")


class Student(BaseModel):
    name: str
    age: int
    course: str


class StudentUpdate(BaseModel):
    name: Optional[str] = None
    age: Optional[int] = None
    course: Optional[str] = None


students: dict[int, Student] = {
    1: Student(name="Alice", age=20, course="Python"),
    2: Student(name="Bob", age=22, course="FastAPI"),
}
next_id = 3


@app.get("/")
def root():
    return {"message": "Welcome to the Student API"}


@app.get("/students")
def get_students():
    return students


@app.get("/students/{student_id}")
def get_student(student_id: int):
    if student_id not in students:
        raise HTTPException(status_code=404, detail="Student not found")
    return students[student_id]


@app.get("/students/search/")
def search_students(course: Optional[str] = None):
    if course is None:
        return students
    return {
        sid: s for sid, s in students.items() if s.course.lower() == course.lower()
    }


@app.post("/students")
def create_student(student: Student):
    global next_id
    students[next_id] = student
    new_id = next_id
    next_id += 1
    return {"id": new_id, "student": student}


@app.put("/students/{student_id}")
def update_student(student_id: int, update: StudentUpdate):
    if student_id not in students:
        raise HTTPException(status_code=404, detail="Student not found")

    stored = students[student_id]
    updated_data = stored.dict()
    for field, value in update.dict(exclude_unset=True).items():
        updated_data[field] = value

    students[student_id] = Student(**updated_data)
    return students[student_id]


@app.delete("/students/{student_id}")
def delete_student(student_id: int):
    if student_id not in students:
        raise HTTPException(status_code=404, detail="Student not found")
    deleted = students.pop(student_id)
    return {"message": f"Deleted student {student_id}", "student": deleted}